const fs = require("fs");
const path = require("path");

// Config
const PROJECT_ROOT = path.resolve(__dirname, "..");
const SC_OUT = path.join(
  PROJECT_ROOT,
  "sc",
  "out",
  "SupplyChain.sol",
  "SupplyChain.json",
);
const WEB_CONFIG_DIR = path.join(
  PROJECT_ROOT,
  "web",
  "src",
  "config",
);
const WEB_CONFIG_FILE = path.join(WEB_CONFIG_DIR, "contracts.ts");

// Detect contract address from Foundry broadcast output
const BROADCAST_JSON = path.join(
  PROJECT_ROOT,
  "sc",
  "broadcast",
  "Deploy.s.sol",
  "31337",
  "run-latest.json",
);

function getContractAddress() {
  if (!fs.existsSync(BROADCAST_JSON)) {
    console.error("Broadcast file not found at", BROADCAST_JSON);
    process.exit(1);
  }
  const data = JSON.parse(fs.readFileSync(BROADCAST_JSON, "utf8"));
  // Try to get from transactions[0].contractAddress
  if (
    data.transactions &&
    Array.isArray(data.transactions) &&
    data.transactions.length > 0 &&
    data.transactions[0].contractAddress
  ) {
    return data.transactions[0].contractAddress;
  }
  // Fallback: try returns[0].value
  if (data.returns && data.returns[0] && data.returns[0].value) {
    return data.returns[0].value;
  }
  console.error("No contract address found in broadcast file");
  process.exit(1);
}

const CONTRACT_ADDRESS = getContractAddress();
const ADMIN_ADDRESS = "0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266";
const NETWORK = {
  chainId: 31337,
  name: "Anvil Local",
  rpcUrl: "http://localhost:8545",
};

function main() {
  if (!fs.existsSync(SC_OUT)) {
    console.error("ABI file not found at", SC_OUT);
    process.exit(1);
  }

  const abiJson = JSON.parse(fs.readFileSync(SC_OUT, "utf8"));
  const abi = abiJson.abi || abiJson;

  // ensure dir
  fs.mkdirSync(WEB_CONFIG_DIR, { recursive: true });

  const content = `// Auto-generated by scripts/generate-contract-config.js
// Do not edit manually unless you know what you're doing

export const CONTRACT_CONFIG = {
  address: "${CONTRACT_ADDRESS}",
  abi: ${JSON.stringify(abi, null, 2)},
  adminAddress: "${ADMIN_ADDRESS}"
};

export const NETWORK_CONFIG = ${JSON.stringify(NETWORK, null, 2)};
`;

  fs.writeFileSync(WEB_CONFIG_FILE, content, "utf8");
  console.log("Wrote", WEB_CONFIG_FILE);
}

main();
